// 傾向判定のしきい値（マジックナンバーを避けて一元管理）。
// share = そのカテゴリ数 / 感情記録の総数。
const REVIEW_THRESHOLDS = {
  /** 拮抗（mixed）とみなす: 最優勢がこの割合に満たない */
  DOMINANT_WEAK: 0.45,
  /** 拮抗（mixed）とみなす: 2位がこの割合以上ある */
  SECOND_PRESENT: 0.3,
  /** ほぼ前向き（all_positive）とみなす: ポジがこの割合以上 */
  ALMOST_ALL: 0.75,
  /** とても重い月（deep_struggle）とみなす: ネガがこの割合以上 */
  OVERWHELMING: 0.75,
} as const;

/** 感情別回数（カテゴリ付き）をカテゴリ合計へ畳み込む */
export function tallyFromCounts(
  counts: { category: EmotionCategory; count: number }[],
): EmotionTally {
  const tally: EmotionTally = { positive: 0, neutral: 0, negative: 0 };
  for (const { category, count } of counts) {
    tally[category] += count;
  }
  return tally;
}

/**
 * カテゴリ傾向からふりかえりのトーンを決める。
 *
 * 同数の tie-break は「positive > neutral > negative」の順でやさしい方に寄せる
 * （責めない方針。傾向が僅差なら前向きに読む）。
 */
export function classifyReviewTone(tally: EmotionTally): ReviewTone {
  const { positive: p, neutral: u, negative: n } = tally;
  const total = p + u + n;
  if (total === 0) return "sparse";

  // 最優勢カテゴリ（tie は positive→neutral→negative の順で優先）
  const ranked: { key: "positive" | "neutral" | "negative"; value: number }[] = [
    { key: "positive", value: p },
    { key: "neutral", value: u },
    { key: "negative", value: n },
  ];
  const sorted = [...ranked].sort((a, b) => b.value - a.value); // 安定ソート＝同数は上記順
  const dominant = sorted[0];
  const second = sorted[1];

  const dominantShare = dominant.value / total;
  const secondShare = second.value / total;

  // 明確な優勢が無く、2位も相応にある → 拮抗（山あり谷あり）
  if (
    dominantShare < REVIEW_THRESHOLDS.DOMINANT_WEAK &&
    secondShare >= REVIEW_THRESHOLDS.SECOND_PRESENT
  ) {
    return "mixed";
  }

  if (dominant.key === "positive") {
    if (n === 0 && dominantShare >= REVIEW_THRESHOLDS.ALMOST_ALL) {
      return "all_positive";
    }
    // ネガが目立つ副次なら「前向き＋しんどさ散見」、そうでなければ「前向き＋穏やか」
    if (n > 0 && n >= u) return "positive_with_negative";
    return "positive_with_neutral";
  }
  if (dominant.key === "neutral") {
    // 穏やか優勢でも、ネガが前向き以上に目立つなら疲れがにじむトーンにする
    if (n > 0 && n >= p) return "calm_with_struggle";
    return "calm_steady";
  }
  // negative 優勢
  if (n / total >= REVIEW_THRESHOLDS.OVERWHELMING) return "deep_struggle";
  // しんどい中でも前向きな夜が一定あれば、光を拾うトーンにする
  if (p > 0 && p >= u) return "persevered_with_light";
  return "persevered";
}

