// 天気への軽い一言（最後に1文だけ添える）。`{weather}` は最多の夜の天気ラベルへ置換。
// 夜の天気はユーザーが「その夜どう感じたか」を主観で選んだもの（要件2.5）。実際の空でも
// あり、その人の心が見た景色でもある——という含みを持たせて、押しつけずに触れる。
// 夜の天気マスタの名前は「雨音の夜」「星空の夜」のように多くが「夜」を含むため、
// 後ろに「〜の夜」を付けず、ラベルをそのまま置く言い回しにする（「夜」の重複を避ける）。
export const WEATHER_NOTES: string[] = [
  "そういえばこの月に多かったのは、あなたが感じたままに選んだ {weather} でした。",
  "空を思い返せば、あなたの目に映った {weather} が多い月だったようです。",
  "この月に多く灯ったのは、あなたの心がそう見た {weather} だったようです。",
  "夜空の記憶をたどると、{weather} の多い月。天気は、その夜の気分とそっと重なります。",
];

/**
 * その月のふりかえりメッセージを1件返す。
 *
 * 傾向でトーンを決め、候補から `year*12 + month` を種に決定的に1本選ぶ。
 * これで同じ月は常に同じ文面（安定）、月が変われば別の文面（飽きない）になる。
 * `{emotion}` は最多感情ラベルへ置換する（無ければ「いちばん多かった気持ち」で代替）。
 * 最多の夜の天気があれば、最後に天気の一言を1文だけ添える（`{weather}` を置換）。
 * 読みやすさのため、文（。）ごとに改行して返す。
 */
export function buildReviewMessage(params: {
  tally: EmotionTally;
  topEmotionLabel: string | null;
  topWeatherLabel?: string | null;
  year: number;
  month: number;
}): string {
  const { tally, topEmotionLabel, topWeatherLabel, year, month } = params;
  const tone = classifyReviewTone(tally);
  const variants = REVIEW_MESSAGES[tone];
  const seed = year * 12 + month;

  let text = variants[seed % variants.length];
  // 天気が記録されている月だけ、最後に軽く天気へ触れる（少しだけ）
  if (topWeatherLabel) {
    text += WEATHER_NOTES[seed % WEATHER_NOTES.length];
  }

  text = text
    .replace(/\{emotion\}/g, topEmotionLabel ?? "いちばん多かった気持ち")
    .replace(/\{weather\}/g, topWeatherLabel ?? "");

  // 文末（。）ごとに改行し、詰まった一段落を読みやすくする。末尾の余分な改行は落とす。
  return text.replace(/。/g, "。\n").replace(/\n+$/, "");
}
