//
// カレンダーの「ふりかえり」タブで、完了した月に限り、その月の感情のカテゴリ傾向
// （ポジ/ニュートラル/ネガの比率）と最多感情に応じたねぎらいの一言を1件表示する。
// 既存のNPCメッセージ（セッション単位・DBシード＋trigger_type）とは別系統で、
// こちらは月次集計ベース・DBに触れない純ロジック＋定数として持つ。
//
// **語るのは、いま選択中の街の住人**（要件7.1・街ごとに1人）。月の記録は街をまたぐ
// ことがあるが、カレンダーを開いている今その街にいる人が振り返る、という考え方にする
// （おやすみのメッセージと同じ）。トーン×住人で1本ずつ持ち、傾向が変われば文面も変わる。
//
// 文体はコンセプト準拠（静か・責めない・急かさない・感嘆符を多用しない・たたえる）。
// しんどい気持ちが多かった月も「それでも続けられたこと」を讃える方向にする。
// 声色の書き分けは docs/NPCセリフ集.md の各住人の方針に合わせる（比喩の引き出しも同じ）。

import type { EmotionCategory } from "@/db/types";

/** その月の感情をカテゴリ別に合算した数 */
export type EmotionTally = {
  positive: number;
  neutral: number;
  negative: number;
};

/** ふりかえり文面のトーン（傾向の型） */
export type ReviewTone =
  | "all_positive" // ほぼ前向きな気持ちで満ちた月
  | "positive_with_neutral" // 前向きが多く、穏やかさも混じる月
  | "positive_with_negative" // 前向き優勢の中に、しんどさが少し散見される月
  | "calm_steady" // 穏やか・いつも通りが中心の、静かに続けた月
  | "calm_with_struggle" // 穏やかさが中心だが、疲れ・しんどさもにじむ月
  | "mixed" // いろいろな気持ちが拮抗した、山あり谷ありの月
  | "persevered_with_light" // しんどさが多い中に、前向きな夜も差し込んだ月
  | "persevered" // しんどい気持ちが多かったが、それでも机に向かった月
  | "deep_struggle" // しんどさが大半を占めた、とても重い月（最大限やさしく）
  | "sparse"; // 気持ちの記録がほとんど無い月（感情記録OFF/未入力）

