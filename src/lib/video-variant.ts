// 背景のループ動画に複数パターンがあるときの選び方（要件2.2）。
//
// 同じ枠（街×時間帯×レベル）に、動きだけが違う動画を複数用意できる。
// 「今夜はどれを流すか」をここで決める。
//
// なぜ乱数を使わないのか:
//   背景の描画は毎分の時刻更新・画面回転・レベルアップ・設定変更のたびに再評価される。
//   そのたびに乱数を引くと、見ている前で動画が別のものへ切り替わってしまう。
//   そこで「学習日をシードにした決定的な選択」とし、同じ学習日のあいだは何度計算しても
//   同じ結果になるようにする。
//
// なぜ暦日ではなく学習日なのか:
//   暦日で切り替えると 0:00 をまたいだ瞬間に背景が入れ替わり、夜通し学習している人の
//   目の前で街が変わる。学習日（18:00〜翌5:00）なら、ひと晩のあいだは変わらない。

/**
 * シード文字列から 0〜count-1 の添字を決める（同じシードなら必ず同じ結果）。
 *
 * ハッシュは FNV-1a（32bit）。暗号用途ではなく、短い文字列を偏りなく散らすためのもの。
 * count が 1 以下なら常に 0 を返す（パターンが1つだけの枠は選ぶ余地がない）。
 *
 * シードには学習日だけでなく街・時間帯・レベルも混ぜること。学習日だけだと、
 * すべての枠が同じ日に一斉に同じ添字を引いてしまう。
 */
export function pickVariantIndex(seed: string, count: number): number {
  if (count <= 1) return 0;

  let hash = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  // 符号なしに直してから割る（Math.imul の結果は符号付き32bitのため負になり得る）
  return (hash >>> 0) % count;
}

/**
 * 動画のパターンを選ぶためのシードを組み立てる。
 * 学習日が変われば結果が変わり、同じ学習日のあいだは変わらない。
 */
export function buildVariantSeed(
  studyDate: string,
  townCode: string,
  timeOfDay: string,
  level: number,
): string {
  return `${studyDate}:${townCode}:${timeOfDay}:lv${level}`;
}
